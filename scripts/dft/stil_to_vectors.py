#!/usr/bin/env python3
"""Convert the stuck-at patterns that TestMAX ATPG writes (STIL) into plain vector files for a tester or a simulator.

usage: stil_to_vectors.py patterns_stuck.stil <out dir>

The Pattern block is a list of  Call "load_unload" {scan_si_i=...; scan_so_o=...;}  and  Call "multiclock_capture"
{_pi=...; _po=...;}  statements. One file per quantity, one line per load/unload (patterns + 1 lines) or capture
(one line per pattern):

  si.mem       scan_si_i, one character 0/1 per scan cell, first character is shifted in first
  so_exp.mem   scan_so_o expected during that load/unload, 1 where H, 0 where L (value of an X is 0, see so_mask)
  so_mask.mem  1 where the output is compared (H or L), 0 where it is a don't care
  pi.mem       the inputs at the capture cycle, order of the _pi group of the STIL
  pi_pulse.mem 1 where that input is pulsed in the capture cycle (clk_i: high 50-70 ns, jtag_tck_i: high 75-90 ns,
               rst_ni: low 75-90 ns of the 100 ns cycle); the value in pi.mem is then the rest level (0, 0, 1)
  po_exp.mem   the outputs strobed at 40 ns of the capture cycle, order of the _po group
  po_mask.mem  1 where compared
  tb_atpg_pins.vh  the pins for sim/tb/tb_atpg.v: sizes, the pin registers and wires, the croc_soc instance, the _pi
               and _po concatenations, and the _pi index of the pins the test bench drives itself
"""
import re
import sys

stil, out = sys.argv[1], sys.argv[2]
text = open(stil).read()


def group(name):
    m = re.search(r'"%s"\s*=\s*\'([^\']*)\'' % re.escape(name), text)
    if not m:
        raise SystemExit("no signal group %s in %s" % (name, stil))
    return re.findall(r'"([^"]+)"', m.group(1))


PI, PO = group("_pi"), group("_po")
body = text[text.index('Pattern "_pattern_"'):]
calls = re.findall(r'Call\s+"(\w+)"\s*\{(.*?)\}', body, re.S)


def fields(s):
    return {k: re.sub(r"\s+", "", v) for k, v in re.findall(r'"([\w\[\]]+)"\s*=\s*([^;]*);', s)}


loads, caps, LEN = [], [], None
for name, s in calls:
    f = fields(s)
    if name == "load_unload":
        si = f.get("scan_si_i")
        if LEN is None and si is not None:
            LEN = len(si)
        loads.append(f)
    elif name == "multiclock_capture":
        pi, po = f["_pi"], f["_po"]
        assert len(pi) == len(PI) and len(po) == len(PO), (len(pi), len(PI), len(po), len(PO))
        caps.append((pi, po))
    else:
        raise SystemExit("unexpected procedure " + name)
assert LEN, "no scan load in the patterns"
loads = [(f.get("scan_si_i", "0" * LEN), f.get("scan_so_o", "X" * LEN)) for f in loads]
for si, so in loads:
    assert len(si) == LEN and len(so) == LEN and set(si) <= set("01"), (len(si), len(so))
assert len(loads) == len(caps) + 1, (len(loads), len(caps))


def w(name, lines):
    open(f"{out}/{name}", "w").write("\n".join(lines) + "\n")


w("si.mem", [si for si, _ in loads])
w("so_exp.mem", ["".join("1" if c == "H" else "0" for c in so) for _, so in loads])
w("so_mask.mem", ["".join("1" if c in "HL" else "0" for c in so) for _, so in loads])
REST = {"clk_i": "0", "rst_ni": "1", "jtag_tck_i": "0"}     # rest level of the pulsed inputs
w("pi.mem", ["".join(REST[PI[i]] if c == "P" else c for i, c in enumerate(pi)) for pi, _ in caps])
w("pi_pulse.mem", ["".join("1" if c == "P" else "0" for c in pi) for pi, _ in caps])
w("po_exp.mem", ["".join("1" if c == "H" else "0" for c in po) for _, po in caps])
w("po_mask.mem", ["".join("1" if c in "HL" else "0" for c in po) for _, po in caps])
pulses = {PI[i] for pi, _ in caps for i, c in enumerate(pi) if c == "P"}
assert pulses <= set(REST), pulses
bad = {c for pi, _ in caps for c in pi} - set("01P")


# test bench include: bit i of the _pi group is bit NPI-1-i of a word ("first in the group" = most significant)
def widths(names):
    wd = {}
    for n in names:
        m = re.match(r"(\w+)(?:\[(\d+)\])?$", n)
        wd[m.group(1)] = max(wd.get(m.group(1), 0), int(m.group(2) or 0) + 1) if m.group(2) else wd.get(m.group(1), 0)
    return wd


def decl(kind, wd):
    return "".join("  %s %s%s;\n" % (kind, "[%d:0] " % (n - 1) if n else "", b) for b, n in wd.items())


NPI, NPO = len(PI), len(PO)
idx = {n: NPI - 1 - i for i, n in enumerate(PI)}
need = ["clk_i", "rst_ni", "testmode_i", "jtag_tck_i", "scan_si_i", "scan_se_i"]
missing = [n for n in need if n not in idx]
if PO[-1] != "scan_so_o":
    raise SystemExit("tb_atpg.v compares scan_so_o as bit 0 of _po, but the last pin of _po is %s" % PO[-1])
if missing:
    raise SystemExit("pins missing in _pi: %s" % missing)
pi_w, po_w = widths(PI), widths(PO)
inst = ", ".join(".%s(%s)" % (b, b) for b in list(pi_w) + list(po_w))
vh = ("// GENERATED by scripts/dft/stil_to_vectors.py from %s; do not edit.\n" % stil.split("/")[-1] +
      "localparam integer NPAT = %d, LEN = %d, NPI = %d, NPO = %d;\n" % (len(caps), LEN, NPI, NPO) +
      "".join("localparam integer PI_%s = %d;\n" % (n.upper(), idx[n]) for n in need) +
      decl("reg", pi_w).replace(";\n", " = 0;\n") + decl("wire", po_w) +
      "  croc_soc dut (%s);\n" % inst +
      "  wire [NPO-1:0] po = {%s};\n" % ", ".join(PO) +
      "  reg [NPI-1:0] st;   // input state, held between vectors\n" +
      "  task drive(input [NPI-1:0] v); begin st = v; {%s} = v; end endtask\n" % ", ".join(PI))
open(f"{out}/tb_atpg_pins.vh", "w").write(vh)
print(f"{len(caps)} capture cycles, {len(loads)} load/unloads of {LEN} cells, {NPI} inputs, {NPO} outputs, "
      f"pulsed inputs: {sorted(pulses)}, other characters: {bad or 'none'}")
