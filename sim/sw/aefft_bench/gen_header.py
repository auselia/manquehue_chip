#!/usr/bin/env python3
"""Write bench.h: the 33-entry Q15 cosine table of the accelerator, and the first block of the recorded AE event
(fw_event1.0) with its setup words and expected result registers, for the benchmark firmware.
The block is a writable array, so the run works in place on it, as the accelerator does."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
FFT = os.path.join(HERE, '..', '..', 'fft')
sys.path.insert(0, os.path.join(FFT, 'model'))
import aefft_model as m
V = os.path.join(FFT, 'vectors')
names = [l.strip() for l in open(os.path.join(V, 'names.txt'))]
rd = lambda f: [int(l, 16) for l in open(os.path.join(V, f)) if l.strip()]
inm, cfg, expf = rd('in.hex'), rd('cfg.hex'), rd('exp_f.hex')
i = names.index('fw_event1.0')
w = lambda v: ','.join('0x%08x' % x for x in v)
open(os.path.join(HERE, 'bench.h'), 'w').write(
    '// Generated by gen_header.py. Do not edit.\n#include <stdint.h>\n'
    'static const int16_t cos_rom[33] = {%s};\n' % ','.join(str(int(v)) for v in m.COS_ROM) +
    'static uint32_t buf[64] = {%s};\n' % w(inm[i * 64:(i + 1) * 64]) +
    'static const uint32_t cfg0[4] = {%s};\n' % w(cfg[i * 4:i * 4 + 4]) +
    '// peak_bin, peak_pow, band, total, td, td_prev, status[5:2]\n'
    'static const uint32_t exp0[7] = {%s};\n' % w(expf[i * 8:i * 8 + 7]))
print('bench.h written')
