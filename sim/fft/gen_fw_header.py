#!/usr/bin/env python3
"""Write sim/sw/aefft_test/vectors.h from sim/fft/vectors: two consecutive blocks of one recorded event
(the second one shows DECAY) and a checksum of the 65-word dump of the first block."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
V = os.path.join(HERE, 'vectors')
names = [l.strip() for l in open(os.path.join(V, 'names.txt'))]
pick = sys.argv[1:] or ['fw_event1.0', 'fw_event1.1']
rd = lambda f: [int(l, 16) for l in open(os.path.join(V, f)) if l.strip()]
inm, cfg, expf, expx = rd('in.hex'), rd('cfg.hex'), rd('exp_f.hex'), rd('exp_x.hex')
out = ['// Generated by sim/fft/gen_fw_header.py from sim/fft/vectors. Do not edit.',
       '#include <stdint.h>', '#define NBLK %d' % len(pick)]
rows_in, rows_cfg, rows_exp = [], [], []
for n in pick:
    i = names.index(n)
    if not rows_in:      # only the first block is stored; the program derives the second one
        rows_in.append('  {' + ','.join('0x%08x' % w for w in inm[i * 64:(i + 1) * 64]) + '}')
    rows_cfg.append('  {' + ','.join('0x%08x' % w for w in cfg[i * 4:(i + 1) * 4]) + '}')
    rows_exp.append('  {' + ','.join('0x%08x' % w for w in expf[i * 8:i * 8 + 7]) + '}')
i0 = names.index(pick[0])
dump_sum = sum(expx[i0 * 65:(i0 + 1) * 65]) & 0xFFFFFFFF
out += ['static const uint32_t blk0[64] = {', ',\n'.join(rows_in).strip()[1:-1], '};',
        'static const uint32_t cfg[NBLK][4] = {', ',\n'.join(rows_cfg), '};',
        '// peak_bin, peak_pow, band, total, td, td_prev, status[5:2]',
        'static const uint32_t expf[NBLK][7] = {', ',\n'.join(rows_exp), '};',
        '#define DUMP_SUM 0x%08xu' % dump_sum, '']
open(os.path.join(HERE, '..', 'sw', 'aefft_test', 'vectors.h'), 'w').write('\n'.join(out))
print('vectors.h written for', pick)
